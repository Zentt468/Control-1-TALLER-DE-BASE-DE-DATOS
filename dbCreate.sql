CREATE TABLE Empresa (
id_empresa SERIAL PRIMARY KEY,
nombre_E VARCHAR(100) NOT NULL,
rut_E VARCHAR(15) NOT NULL
);

CREATE TABLE Local (
id_local SERIAL PRIMARY KEY,
id_empresa INT NOT NULL REFERENCES Empresa(id_empresa) ON UPDATE CASCADE ON DELETE RESTRICT,
nombre_L VARCHAR(100) NOT NULL,
direccion_L VARCHAR(100) NOT NULL,
comuna_L VARCHAR(100) NOT NULL
);

CREATE TABLE Servicio (
id_servicio SERIAL PRIMARY KEY,
id_local INT NOT NULL REFERENCES Local(id_local) ON UPDATE CASCADE ON DELETE RESTRICT,
nombre_S VARCHAR(100) NOT NULL,
descripcion_S TEXT

);

CREATE TABLE Cargo (
id_cargo SERIAL PRIMARY KEY,
nombre_cargo VARCHAR(100) NOT NULL
);

CREATE TABLE Empleado (
id_empleado SERIAL PRIMARY KEY,
id_local INT NOT NULL REFERENCES Local(id_local) ON UPDATE CASCADE ON DELETE RESTRICT,
id_cargo INT NOT NULL REFERENCES Cargo(id_cargo) ON UPDATE CASCADE ON DELETE RESTRICT,
nombre_T VARCHAR(100) NOT NULL,
rut_T VARCHAR(100) NOT NULL,
correo_T VARCHAR(100) NOT NULL
);

CREATE TABLE EstadoP (
id_estado_p SERIAL PRIMARY KEY,
nombre_estado_p VARCHAR(15) NOT NULL
);

CREATE TABLE Vehiculo (
id_vehiculo SERIAL PRIMARY KEY,
patente VARCHAR(7) NOT NULL,
marca VARCHAR(30) NOT NULL,
modelo VARCHAR(30) NOT NULL
);

CREATE TABLE Presupuesto (
id_presupuesto SERIAL PRIMARY KEY,
id_local INT NOT NULL REFERENCES Local(id_local) ON UPDATE CASCADE ON DELETE RESTRICT,
id_estado_p INT NOT NULL REFERENCES EstadoP(id_estado_p) ON UPDATE CASCADE ON DELETE RESTRICT,
id_empleado INT NOT NULL REFERENCES Empleado(id_empleado) ON UPDATE CASCADE ON DELETE RESTRICT,
id_vehiculo INT NOT NULL REFERENCES Vehiculo(id_vehiculo) ON UPDATE CASCADE ON DELETE RESTRICT,
fecha DATE NOT NULL,
monto_total INT NOT NULL
);

CREATE TABLE Sueldo (
id_sueldo SERIAL PRIMARY KEY,
id_empleado INT NOT NULL REFERENCES Empleado(id_empleado) ON UPDATE CASCADE ON DELETE RESTRICT,
cantidad INT NOT NULL,
fecha_pago DATE NOT NULL
);

CREATE TABLE Tarea (
id_tarea SERIAL PRIMARY KEY,
nombre_tarea VARCHAR(100) NOT NULL,
costo_tarea INT NOT NULL
);

CREATE TABLE Detalle_Servicio (
id_detalle_servicio SERIAL PRIMARY KEY,
id_servicio INT NOT NULL REFERENCES Servicio(id_servicio) ON UPDATE CASCADE ON DELETE RESTRICT,
id_tarea INT NOT NULL REFERENCES Tarea(id_tarea) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE EstadoT (
id_estado_t SERIAL PRIMARY KEY,
nombre_estado_t VARCHAR(100) NOT NULL
);

CREATE TABLE Detalle_Presupuesto (
id_detalle_presupuesto SERIAL PRIMARY KEY,
id_tarea INT NOT NULL REFERENCES Tarea(id_tarea) ON UPDATE CASCADE ON DELETE RESTRICT,
id_presupuesto INT NOT NULL REFERENCES Presupuesto(id_presupuesto) ON UPDATE CASCADE ON DELETE RESTRICT
);

CREATE TABLE Trabajo (
id_trabajo SERIAL PRIMARY KEY,
id_presupuesto INT NOT NULL REFERENCES Presupuesto(id_presupuesto) ON UPDATE CASCADE ON DELETE RESTRICT,
id_local INT NOT NULL REFERENCES Local(id_local) ON UPDATE CASCADE ON DELETE RESTRICT,
id_estado_t INT NOT NULL REFERENCES EstadoT(id_estado_t) ON UPDATE CASCADE ON DELETE RESTRICT,
id_empleado_jefe INT NOT NULL REFERENCES Empleado(id_empleado) ON UPDATE CASCADE ON DELETE RESTRICT,
fecha_inicio DATE NOT NULL,
fecha_fin DATE NOT NULL
);

CREATE TABLE Detalle_Trabajo (
id_detalle_trabajo SERIAL PRIMARY KEY,
id_tarea INT NOT NULL REFERENCES Tarea(id_tarea) ON UPDATE CASCADE ON DELETE RESTRICT,
id_trabajo INT NOT NULL REFERENCES Trabajo(id_trabajo) ON UPDATE CASCADE ON DELETE RESTRICT,
id_estado_t INT NOT NULL REFERENCES EstadoT(id_estado_t) ON UPDATE CASCADE ON DELETE RESTRICT,
id_empleado INT NOT NULL REFERENCES Empleado(id_empleado) ON UPDATE CASCADE ON DELETE RESTRICT,
detalle TEXT
);
